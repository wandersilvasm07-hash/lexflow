import type { NextConfig } from "next";

/**
 * Política de segurança de conteúdo (CSP).
 * Nonces são incompatíveis com a pré-renderização parcial que a aplicação usa
 * (ver docs do Next.js, "Content Security Policy"), por isso os scripts inline
 * do próprio Next continuam permitidos; tudo o resto fica restrito à própria
 * origem e aos serviços necessários (Supabase, Stripe e Meta só para redirecionamentos).
 */
const isDev = process.env.NODE_ENV !== "production";
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://*.supabase.co",
  "font-src 'self'",
  "connect-src 'self' https://*.supabase.co wss://*.supabase.co",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self' https://checkout.stripe.com https://billing.stripe.com https://www.facebook.com",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

/** Cabeçalhos de segurança aplicados a todas as respostas. */
const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
];

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  experimental: {
    // Importação de documentos para a base jurídica (PDF/DOCX até 4 MB).
    serverActions: { bodySizeLimit: "4.5mb" },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
